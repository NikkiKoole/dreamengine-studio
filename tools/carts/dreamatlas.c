// md_quantize, verbatim: nearest note of the scale mask, searching down before up.
static int quantize(int note, int root, int scale) {
    static const unsigned masks[13] = { 0xfff, 0x5ad, 0xab5, 0x6ad, 0x4a9, 0x295, 0x555, 0x5ab, 0x6cd, 0x9ad, 0x9cd, 0x9b5, 0x9b3 };
    note = bound(note, 24, 96); root = bound(root, 0, 11);
    unsigned mask = masks[bound(scale, 0, 12)];
    for (int d = 0; d < 12; d++) {
        int lo = note - d, hi = note + d;
        if (lo >= 24 && (mask & (1u << ((lo - root + 12) % 12)))) return lo;
        if (hi <= 96 && (mask & (1u << ((hi - root + 12) % 12)))) return hi;
    }
    return note;
}
// md_hit, verbatim: k hits spread over n steps (their Bresenham form of Bjorklund).
static int md_hit(unsigned s, unsigned h, unsigned l, unsigned r) {
    if (!l || l > 32) return 0;
    if (h > l) h = l;
    return (((s + r) % l) * h) % l < h;
}

