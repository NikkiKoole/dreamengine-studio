// MARMALADE JAM borrows Playtime's drum jam (its docs/DRUM-JAM.md): a standard four-on-the-floor
// at 125 with layers that come and go on 8-bar phrases, instead of a factory biome's fixed scene.
// Roles: 0 kick (4 in 16), 1 hat (the offbeats), 2 clap (2 and 4), 3 bass (6 in 16, rotated off
// every kick), 4 lead (a Rings pluck, 5 in 13: the one odd length, so it drifts against the bar),
// 5 keys (3 in 8 at eighths = the tresillo). I-vi-IV-V, two bars a chord. The randomness is the
// factory kind: per-hit chance, the jump macro, a seed re-rolled every two bars (locked 0).
// LANTERN BAZAAR is the hand-percussion one, on our two extra engines: a low tabla (bayan, with
// its pitch swoop) 3 in 16 and a high one (dayan, tuned, wandering with the jump macro) 7 in 16, a
// guiro scraping the tresillo, a round bass, a Rings marimba 5 in 12 (three against the bar's four)
// and a quijada that rattles once every two bars, just before the turnaround. D dorian at 100,
// i-IV-i-v. Its jam builds from the bayan and the guiro; the high tabla plays the fills.
// LEVELS in our biomes are set by measured stems, not the factory fit: upstream's balance puts its
// quiet Plaits kick ~20 dB under a loud round bass, which is wrong for a groove. Solo RMS (100 s,
// DA_SOLO): kick ≈ bass ≈ -36 dB, keys/lead/tabla a few dB under, transients (guiro, quijada) by peak.
// MOON GARDEN is Moon Meadow (factory id 10) with hand percussion folded in: its choir pad,
// 2-in-19 harmonic drone and Rings kept as they are (same tempo, key, grain tape; family Mist, so
// the ambient sends and tides), and its other three tracks swapped for a low tabla, a high tabla
// and a soft fading scrape. It jams gently: the mist first, the percussion one phrase at a time,
// and its breakdown takes only the percussion away.
// SLOW BREW is Playtime's brew style (its src/music-brew.lua, after Ronnie Foster) broken into
// cycles, on brew's own instruments copied from Playtime's synth.lua patches: the bapKick drumhead,
// the snare, the agogo-like bell pair (high and low in turn), hUpright (the finger-plucked upright),
// brewOrgan (thin tonewheel registration through a slow Leslie) and brewGuitar. Brew's key (F minor),
// tempo and its one-chord-a-bar i-III-VI; NOT its riff: the bass is 13 hits over 24 eighths (a
// 3-bar cycle, as brew's riff is) wandering in the scale. The organ voices each chord ROOTLESS (3rd,
// 5th, 7th, 9th: Fm9, Abmaj9, Dbmaj9, brew's colours) every three beats; the guitar strums small
// shapes on a 10-eighth (5/4) cycle; the agogo plays 5 in 12. The bar, the bells' three-against-
// four, the organ's dotted halves and the guitar's fives meet again only every few bars; the bass
// and the chords every 3. The bells keep time where brew has a hat (six tracks).
// MIPO BAND is Puppetmaker 2's band (Mipo Puppetmaker; the playtime docs/PUPPETMAKER-SOUND.md §1a
// and its puppetmaker style), on Playtime's synth patches for it: the CR-78 conga (low), the two
// bongos as one alternating low/high pair (+7), the tambourine (a short jingle high-passed at
// 6.5 kHz), the guiro (INSTR_SCRAPE), the babirhodes "lick" (one ROLLED six-note chord, root + 0 7 16
// 19 21 24, up-strummed +29 +23 +23 +76 +40 ms, ringing 3 s, floating in at a wandering root: the
// same voicing every time, only the pitch moves) and the ringing triangle on 6 and 14. 60 BPM in
// 16ths, swing 52, chromatic, and nothing resolves. The Mipos' singing (pi/po/ba/bi on INSTR_VOICE)
// was tried and cut: it sounded awful. The choked triangle and the blips have no track left.
// CR-78 BOSSA is the CR-78's own BOSSA NOVA preset (the cr78 cart, its voices rebuilt from the
