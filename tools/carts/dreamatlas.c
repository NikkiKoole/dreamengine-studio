// ── the Lo-Fi kit: tools/generate_lofi.py, ported ───────────────────────────
// 5 banks × 8 pads of 16 kHz one-shots from decaying sines and filtered noise. Rendered at 16 kHz
// exactly as upstream, then resampled to the engine rate with the SAME linear interpolation their
// player uses, through their one-pole tone filter and decay envelope (the default pad settings,
// baked in, since the factory biomes never change them). The 16 kHz band limit IS the lo-fi.
static float kit_pcm[24000];
static unsigned kit_rng;
static float kit_noise(void) { return (rword(&kit_rng) >> 8) * (2.0f / 16777216.0f) - 1.0f; }
static void kit_render(int bank) {
    static const float lengths[8] = { .22f, .13f, .055f, .10f, .035f, .12f, .10f, .24f };
    static const float gains[8]   = { .82f, .70f, .55f, .65f, .5f, .42f, .50f, .48f };
    static float raw[4000];
    const float TAU = 6.2831853f, rate = 16000;
    for (int pad = 0; pad < 8; pad++) {
        kit_rng = 0x13d057u + bank * 37 + pad * 7919 + 1;
        int N = (int)(lengths[pad] * rate + 0.5f);
        float phase = 0, lp = 0;
        for (int i = 0; i < N; i++) {
            float t = i / rate, nz = kit_noise(), x = 0, win = sinf(3.1415927f * i / N); win *= win;
            lp += (nz - lp) * (.15f + .10f * bank);
            switch (pad) {
            case 0: { float f = 43 + bank * 8 + 100 * expf(-t * 80); phase += TAU * f / rate;
                      x = (sinf(phase) + .06f * lp * expf(-t * 90)) * expf(-t * (18 + bank * 3)); } break;
            case 1: x = (lp * .8f + sinf(t * TAU * (165 + bank * 40)) * .2f) * expf(-t * (30 + bank * 8)); break;
            case 2: x = (nz - lp) * expf(-t * (80 - bank * 12)) * .5f; break;
            case 3: x = (sinf(t * TAU * (390 + bank * 90)) + .27f * sinf(t * TAU * (610 + bank * 200))) * expf(-t * (60 - bank * 6)); break;
            case 4: x = (lp * .5f + sinf(t * TAU * (720 + bank * 210)) * .3f) * expf(-t * 160); break;
            case 5: x = lp * win * (.9f + .1f * sinf(t * 81)); break;
            case 6: x = (lp * .12f + ((rword(&kit_rng) % 1000) < (unsigned)((.012f + bank * .006f) * 1000) ? nz * .8f : 0)) * win; break;
            default: x = (lp * .7f + .13f * sinf(t * TAU * (135 + bank * 47))) * win; break;
            }
            if (bank == 3) {          // Found Objects: damped wooden / ceramic resonances, papery transients
                if (pad == 0) x = (sinf(t * TAU * 62) + .25f * sinf(t * TAU * 118)) * expf(-t * 25);
                else if (pad == 4) x = (.7f * sinf(t * TAU * 310) + .3f * lp) * expf(-t * 100);
                else if (pad == 1 || pad == 2) x = (nz - lp) * (.6f + .4f * sinf(t * TAU * (39 + pad * 11))) * expf(-t * (35 + pad * 22));
                else if (pad == 3) x = (sinf(t * TAU * 290) + .37f * sinf(t * TAU * 431) + .18f * sinf(t * TAU * 687)) * expf(-t * 48);
                else if (pad == 7) x = (sinf(t * TAU * 196) + .3f * sinf(t * TAU * 293.66f) + lp * .18f) * win;
            }
            if (bank == 4) {          // Velour Tape: softened attacks, warm pitched fragments, fluttering air
                if (pad == 0) x = sinf(t * TAU * (48 + 45 * expf(-t * 60))) * expf(-t * 18);
                else if (pad == 1) x = (lp * .8f + .15f * sinf(t * TAU * 180)) * expf(-t * 26);
                else if (pad == 2) x = lp * expf(-t * 60);
                else if (pad == 3 || pad == 4) x = (sinf(t * TAU * (pad == 3 ? 220 : 330)) + .25f * sinf(t * TAU * (pad == 3 ? 440 : 495))) * expf(-t * (pad == 3 ? 30 : 85));
                else if (pad == 7) x = (sinf(t * TAU * 130.81f) + .45f * sinf(t * TAU * 196) + .3f * sinf(t * TAU * 261.63f)) * win;
            }
            raw[i] = x;
        }
        float mean = 0, peak = 1e-6f;
        for (int i = 0; i < N; i++) mean += raw[i];
        mean /= N;
        for (int i = 0; i < N; i++) {
            float e = fminf(1.0f, fminf(i / 16.0f, (N - 1 - i) / 64.0f));
            raw[i] = (raw[i] - mean) * e;
            if (fabsf(raw[i]) > peak) peak = fabsf(raw[i]);
        }
        float g = gains[pad] / peak;
        // play it out at 44.1 kHz the way kit_mix does: linear read at 16000/44100, one-pole tone,
        // exponential decay (pad defaults: cutoff 650 → coef .02+.55·.65², decay 850 → .008+.9·.85² s)
        float rate_step = 16000.0f / DA_SR, cut = .02f + .55f * .65f * .65f;
        float dec = 1.0f - 1.0f / (DA_SR * (.008f + .9f * .85f * .85f)), env = 1, lpo = 0;
        int n = 0;
        for (float p = 0; p < N - 1 && n < 24000; p += rate_step) {
            int a = (int)p; float f = p - a;
            float x = (raw[a] + (raw[a + 1] - raw[a]) * f) * g;
            lpo += (x - lpo) * cut;
            kit_pcm[n++] = lpo * env * fminf(1.0f, p / 16.0f);
            env *= dec;
        }
        // their mix runs ~6-10 dB hotter than ours for the kit (×1.9 master + no slot level), and
        // the baked tone filter sheds peak: re-level each pad to its authored peak after the bake
        float pk = 1e-6f; for (int i = 0; i < n; i++) if (fabsf(kit_pcm[i]) > pk) pk = fabsf(kit_pcm[i]);
        for (int i = 0; i < n; i++) kit_pcm[i] *= gains[pad] / pk;
        sample_load(pad, kit_pcm, n);
        instrument(SL_PAD + pad, INSTR_SAMPLE, 0, 2000, 7, 30);
        instrument_sample(SL_PAD + pad, pad, 60);
    }
    kit_ready_bank = bank;
}

// ── scene(): factory row + the defaults upstream derives in code ────────────
static void kit_pattern(int g) {
    for (int p = 0; p < 8; p++) S.kit_gates[p] = 0;
    for (unsigned n = 0; n < 32; n++) {
        if (g == 0) { if (n % 8 == 0) S.kit_gates[0] |= 1u << n; if (n % 8 == 4) S.kit_gates[1] |= 1u << n; if (n % 4 == 2) S.kit_gates[2] |= 1u << n; if (n % 16 == 13) S.kit_gates[6] |= 1u << n; }
        if (g == 1) { if (n % 8 == 0 || n % 16 == 11) S.kit_gates[0] |= 1u << n; if (n % 8 == 4) S.kit_gates[1] |= 1u << n; if (n % 2 == 0) S.kit_gates[2] |= 1u << n; if (n % 16 == 7) S.kit_gates[3] |= 1u << n; }
        if (g == 2) { if (n % 16 == 0) S.kit_gates[0] |= 1u << n; if (n % 16 == 7) S.kit_gates[3] |= 1u << n; if (n % 16 == 12) S.kit_gates[7] |= 1u << n; if (n % 8 == 3) S.kit_gates[6] |= 1u << n; }
        if (g == 3) { if (n % 16 == 0) S.kit_gates[5] |= 1u << n; if (n % 8 == 5) S.kit_gates[6] |= 1u << n; if (n % 16 == 11) S.kit_gates[7] |= 1u << n; }
    }
}
static void set_phrase(int tr, const signed char *ph, int vel0, int vbase, int vmod, int gbase, int gmod, int gk, int salt) {
    S.seq_on[tr] = 1; S.seq_len[tr] = 16;
    for (int k = 0; k < 16; k++) {
        int off = ph[k];
        S.seq[tr][k].note = off < 0 ? 0 : (unsigned char)bound(quantize(S.b.tr[tr].note + off, S.b.root, S.b.scale), 24, 96);
        S.seq[tr][k].vel = (unsigned char)(k == 0 ? vel0 : vbase + (k * 3 + salt) % vmod);
        S.seq[tr][k].chance = 100;
        S.seq[tr][k].gate = (unsigned char)(gbase + (k * gk) % gmod);
    }
}
