static void kit_pattern(int g) {
    for (int p = 0; p < 8; p++) S.kit_gates[p] = 0;
    for (unsigned n = 0; n < 32; n++) {
        if (g == 0) { if (n % 8 == 0) S.kit_gates[0] |= 1u << n; if (n % 8 == 4) S.kit_gates[1] |= 1u << n; if (n % 4 == 2) S.kit_gates[2] |= 1u << n; if (n % 16 == 13) S.kit_gates[6] |= 1u << n; }
        if (g == 1) { if (n % 8 == 0 || n % 16 == 11) S.kit_gates[0] |= 1u << n; if (n % 8 == 4) S.kit_gates[1] |= 1u << n; if (n % 2 == 0) S.kit_gates[2] |= 1u << n; if (n % 16 == 7) S.kit_gates[3] |= 1u << n; }
        if (g == 2) { if (n % 16 == 0) S.kit_gates[0] |= 1u << n; if (n % 16 == 7) S.kit_gates[3] |= 1u << n; if (n % 16 == 12) S.kit_gates[7] |= 1u << n; if (n % 8 == 3) S.kit_gates[6] |= 1u << n; }
        if (g == 3) { if (n % 16 == 0) S.kit_gates[5] |= 1u << n; if (n % 8 == 5) S.kit_gates[6] |= 1u << n; if (n % 16 == 11) S.kit_gates[7] |= 1u << n; }
    }
}
static void set_phrase(int tr, const signed char *ph, int vel0, int vbase, int vmod, int gbase, int gmod, int gk, int salt) {
    S.seq_on[tr] = 1; S.seq_len[tr] = 16;
    for (int k = 0; k < 16; k++) {
        int off = ph[k];
        S.seq[tr][k].note = off < 0 ? 0 : (unsigned char)bound(quantize(S.b.tr[tr].note + off, S.b.root, S.b.scale), 24, 96);
        S.seq[tr][k].vel = (unsigned char)(k == 0 ? vel0 : vbase + (k * 3 + salt) % vmod);
        S.seq[tr][k].chance = 100;
        S.seq[tr][k].gate = (unsigned char)(gbase + (k * gk) % gmod);
    }
}
