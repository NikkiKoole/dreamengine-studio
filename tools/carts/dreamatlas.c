// ── KICK: Plaits' AnalogBassDrum, PORTED (Emilie Gillet, MIT), the trigger path only ─────────
// Mapping it onto INSTR_SINE gave a sustained thump with no click, 20 dB too loud in the balance.
// The real one is a 1 ms pulse that rings a band-pass SVF and leaks straight out through a
// one-pole at 4·f0·2^(9·tone): a loud click over a body sitting ~15-25 dB under it. Rendered
// once per (note, tone, decay, harm) into sample slot 8+i, then played as INSTR_SAMPLE at its
// own note. Dreams calls it as: accent = velocity, tone·(.65+.35·tone), attack FM = harm·.75,
// self FM .12, no envelope after. Rendered at accent 1; fire() scales by the pulse height.
#define KICK_MAX 88200      // 2 s at 44.1 kHz; decay 1.0 on a low note rings ~1.1 s
static float kick_pcm[KICK_MAX * SNARE_VARS];   // 8 s: the sample slot's ceiling (SOUND_REC_LEN)
static float drum_key[6][5];      // what sample slot 8+i holds: model, note and the three knobs
static int drum_cached(int i, int m, int note, float a, float b, float c) {
    float key[5] = { (float)m, (float)note, a, b, c };
    if (!memcmp(key, drum_key[i], sizeof key)) return 1;
    memcpy(drum_key[i], key, sizeof key); return 0;
}
static float kick_diode(float x) { if (x >= 0) return x; x *= 2; return .7f * x / (1 + fabsf(x)); }
static void drum_load(int i, float peak) {   // trim kick_pcm's tail at -80 dB re peak, short fade, load
    int n = KICK_MAX;
    while (n > 64 && fabsf(kick_pcm[n - 1]) < peak * 1e-4f) n--;
    for (int k = 0; k < 64 && k < n; k++) kick_pcm[n - 1 - k] *= k / 64.0f;
    sample_load(8 + i, kick_pcm, n);
}
static void kick_render(int i, int note, float tone, float decay, float attack_fm) {
    if (drum_cached(i, M_KICK, note, tone, decay, attack_fm)) return;
    const float f0 = note_hz(note) / DA_SR, accent = 1, self_fm = .12f;
    const int trig_len = (int)(1e-3f * DA_SR), fm_len = (int)(6e-3f * DA_SR);
    const float pulse_decay = .2e-3f * DA_SR, pulse_filter = .1e-3f * DA_SR, retrig_len = .05f * DA_SR;
    const float scale = .001f / f0, q = 1500 * powf(2, decay * 80 / 12);
    const float tone_f = fminf(4 * f0 * powf(2, tone * 108 / 12), 1), leak = .08f * (tone + .25f);
    int pulse_left = trig_len, fm_left = fm_len;
    float pulse_s = 0, height = 3 + 7 * accent, pulse_lp = 0, fm_lp = 0, retrig = 0, lp = 0, tone_lp = 0;
    float s1 = 0, s2 = 0, peak = 1e-9f;
    for (int k = 0; k < KICK_MAX; k++) {
        float pulse;
        if (pulse_left) { --pulse_left; pulse = pulse_left ? height : height - 1; pulse_s = pulse; }
        else { pulse_s *= 1 - 1 / pulse_decay; pulse = pulse_s; }
        pulse_lp += (pulse - pulse_lp) / pulse_filter;
        pulse = kick_diode((pulse - pulse_lp) + pulse * .044f);
        float fm = 0;
        if (fm_left) { --fm_left; fm = 1; retrig = fm_left ? 0 : -.8f; }
        else retrig *= 1 - 1 / retrig_len;
        fm_lp += (fm - fm_lp) / pulse_filter;
        float punch = .7f + kick_diode(10 * lp - 1);
        float f = f0 * (1 + fm_lp * 1.7f * attack_fm + punch * .08f * self_fm);
        f = fminf(.4f, fmaxf(0, f));
        // stmlib Svf, FREQUENCY_DIRTY tan, band-pass + low-pass taps
        float g = f * (3.14159265f + .3736f * 31.00627668f * f * f), r = 1 / (1 + q * f);
        float h = 1 / (1 + r * g + g * g);
        float hp = ((pulse - retrig * .2f) * scale - r * s1 - g * s1 - s2) * h;
        float bp = g * hp + s1; s1 = g * hp + bp;
        lp = g * bp + s2; s2 = g * bp + lp;
        tone_lp += tone_f * (pulse * leak + bp - tone_lp);
        kick_pcm[k] = tone_lp;
        if (fabsf(tone_lp) > peak) peak = fabsf(tone_lp);
    }
    drum_load(i, peak);
}

// ── SNARE: Plaits' AnalogSnareDrum, PORTED (Emilie Gillet, MIT), the trigger path only ───────
// Mapped onto a noise slot + a triangle it stayed ~5× too bright: our 2-pole low-pass leaves a
// long bright tail where Plaits' noise goes through a BAND-pass at 16·f0. The real one: a 1 ms
// pulse rings five SVF modes (1, 2, 3.18, 4.16, 5.62 × f0; two below tone 2/3, the 808, five
// above), soft-clipped, under half-wave noise band-passed at 16·f0 with Q 1+1.5f. Body × (1 −
// snappy), noise × snappy. Dreams calls it with accent = velocity, tone·(.7+.3·tone), snappy =
// harm·.85, no envelope after. Accent only moves the body's pulse, so it is rendered at the
// default .8 and played at its own level. Upstream draws fresh noise per hit: we render four
// draws into one sample and rotate them over SL_TRACK+i and three SL_ROUND slots.
static float svf_g_fast(float f) { float f2 = f * f; return f * (3.14159265f + f2 * (.326f * 31.00627668f + .1823f * 306.0196848f * f2)); }
static float soft_clip(float x) { return x < -3 ? -1 : x > 3 ? 1 : x * (27 + x * x) / (27 + 9 * x * x); }
static void snare_render(int i, int note, float tone, float decay, float snappy) {
    if (drum_cached(i, M_SNARE, note, tone, decay, snappy)) return;
    const float f0 = note_hz(note) / DA_SR, accent = .8f;
    const float decay_xt = decay * (1 + decay * (decay - 1));
    const int trig_len = (int)(1e-3f * DA_SR);
    const float pulse_decay = .1e-3f * DA_SR, q = 2000 * powf(2, decay_xt * 84 / 12);
    const float noise_dec = 1 - .0017f * powf(2, -decay * (50 + snappy * 10) / 12);
    const float leak = snappy * (2 - snappy) * .1f;
    snappy = fminf(1, fmaxf(0, snappy * 1.1f - .05f));
    static const float ratio[5] = { 1, 2, 3.18f, 4.16f, 5.62f };
    float g[5], r[5], h[5], s1[5] = {0}, s2[5] = {0}, gain[5];
    for (int k = 0; k < 5; k++) {
        float f = fminf(f0 * ratio[k], .499f);
        g[k] = svf_g_fast(f); r[k] = 1 / (1 + f * (k ? q * .25f : q)); h[k] = 1 / (1 + r[k] * g[k] + g[k] * g[k]);
    }
    if (tone < .666667f) {
        tone *= 1.5f;
        gain[0] = 1.5f + (1 - tone) * (1 - tone) * 4.5f; gain[1] = 2 * tone + .15f;
        gain[2] = gain[3] = gain[4] = 0;
    } else {
        tone = (tone - .666667f) * 3;
        gain[0] = 1.5f - tone * .5f; gain[1] = 2.15f - tone * .7f;
        for (int k = 2; k < 5; k++) { gain[k] = tone; tone *= tone; }
    }
    float fn = fminf(f0 * 16, .499f), ng = svf_g_fast(fn), nr = 1 / (1 + fn * 1.5f), nh = 1 / (1 + nr * ng + ng * ng);
    float peak = 1e-9f;
    for (int v = 0; v < SNARE_VARS; v++) {          // the same body, a fresh noise draw each
    float *out = kick_pcm + v * KICK_MAX;
    for (int m = 0; m < 5; m++) s1[m] = s2[m] = 0;
    float n1 = 0, n2 = 0, pulse_s = 0, pulse_lp = 0, height = 3 + 7 * accent, env = 2;
    unsigned rng = 0x9E3779B9u ^ (unsigned)(note * 7919 + i * 131 + v * 104729);
    int pulse_left = trig_len;
    for (int k = 0; k < KICK_MAX; k++) {
        float pulse;
        if (pulse_left) { --pulse_left; pulse = pulse_left ? height : height - 1; pulse_s = pulse; }
        else { pulse_s *= 1 - 1 / pulse_decay; pulse = pulse_s; }
        pulse_lp += .75f * (pulse - pulse_lp);
        float shell = 0;
        for (int m = 0; m < 5; m++) {
            float x = m ? .026f * pulse : (pulse - pulse_lp) + .006f * pulse;
            float hp = (x - r[m] * s1[m] - g[m] * s1[m] - s2[m]) * h[m];
            float bp = g[m] * hp + s1[m]; s1[m] = g[m] * hp + bp;
            float lp = g[m] * bp + s2[m]; s2[m] = g[m] * bp + lp;
            shell += gain[m] * (bp + x * leak);
        }
        rng = rng * 1664525u + 1013904223u;
        float nz = 2 * ((rng >> 8) * (1.0f / 16777216.0f)) - 1; if (nz < 0) nz = 0;
        env *= noise_dec;
        nz *= env * snappy * 2;
        float hp = (nz - nr * n1 - ng * n1 - n2) * nh;
        float bp = ng * hp + n1; n1 = ng * hp + bp;
        float lp = ng * bp + n2; n2 = ng * bp + lp;
        float y = bp + soft_clip(shell) * (1 - snappy);
        out[k] = y;
        if (fabsf(y) > peak) peak = fabsf(y);
    }
    }
    // one length for all four (the longest tail above -80 dB), packed back to back so each
    // variant is an equal quarter of the sample: instrument_sample_region picks one per slot
    int n = 64;
    for (int v = 0; v < SNARE_VARS; v++) {
        int len = KICK_MAX; const float *o = kick_pcm + v * KICK_MAX;
        while (len > n && fabsf(o[len - 1]) < peak * 1e-4f) len--;
        if (len > n) n = len;
    }
    for (int v = 0; v < SNARE_VARS; v++) {
        memmove(kick_pcm + v * n, kick_pcm + v * KICK_MAX, n * sizeof(float));
        for (int k = 0; k < 64; k++) kick_pcm[v * n + n - 1 - k] *= k / 64.0f;
    }
    sample_load(8 + i, kick_pcm, n * SNARE_VARS);
}

static void config_track(int i) {
    const DaTrack *t = &S.b.tr[i];
    int s = SL_TRACK + i, l = SL_LAYER + i, m = t->model;
    float tone = tone_of(i), harm = unit(t->harm), shape = unit(t->shape), dec = unit(t->decay);
    int A = env_attack_ms(i), D = env_decay_ms(i);
    // a REDEFINED slot keeps its old env/filter/drive/unison/sync — switch them all off first
    for (int k = 0; k < 2; k++) {
        int sl = k ? l : s;
        instrument_env(sl, 0, ENV_PITCH, 0, 10, 0); instrument_env(sl, 1, ENV_CUTOFF_OCT, 0, 10, 0);
        instrument_filter(sl, FILTER_OFF, 20000, 0); instrument_drive(sl, 0);
        instrument_unison(sl, 1, 0); instrument_sync(sl, 0);
    }
    instrument_level(l, 0);
    // our models set per-engine modes, mono, vibrato and a Leslie, which a factory model never
    // touches: put a slot back at the defaults when it holds, or held, one of ours (factory renders
    // stay byte-identical: a slot that only ever held factory models is never touched here)
    static int held_ours[6], had_leslie[6];
    if (m >= M_TABLA || held_ours[i]) {
        static const float mode_default[7] = { 0, 0, .5f, .5f, .5f, .5f, 0 };   // as Playtime's MODE_DEFAULTS
        for (int k = 0; k < 7; k++) instrument_mode(s, k, mode_default[k]);
        instrument_mono(s, 0); instrument_vibrato(s, 1);
        instrument_release_shape(s, RELEASE_LINEAR); instrument_release_shape(l, RELEASE_LINEAR);
        if (had_leslie[i] && m != M_ORGAN) { instrument_leslie(s, 1, 0, .5f, 0, 0); had_leslie[i] = 0; }
    }
    held_ours[i] = m >= M_TABLA;
    switch (m) {
    case M_KICK:      // Plaits analog bass drum, ported above and rendered to sample slot 8+i
        kick_render(i, t->note, tone * (.65f + .35f * tone), dec, harm * .75f);
        instrument(s, INSTR_SAMPLE, 0, 2000, 7, 30);
        instrument_sample(s, 8 + i, t->note); instrument_sample_region(s, 0, 1); break;
    case M_SNARE:     // Plaits analog snare, ported above and rendered to sample slot 8+i
        snare_render(i, t->note, tone * (.7f + .3f * tone), dec, harm * .85f);
        for (int v = 0; v < SNARE_VARS; v++) {      // variant v on its own slot, the rest below copies s
            int sl = v ? SL_ROUND + 3 * i + v - 1 : s;
            instrument(sl, INSTR_SAMPLE, 0, 2000, 7, 30);
            instrument_sample(sl, 8 + i, t->note);
            instrument_sample_region(sl, (float)v / SNARE_VARS, (float)(v + 1) / SNARE_VARS);
        }
        break;
    case M_HAT:       // Plaits hi-hat: six inharmonic squares, the 808 metal bank
        instrument(s, INSTR_METAL, 0, 30 + (int)(dec * 700), 0, 30);
        instrument_harmonics(s, tone); instrument_timbre(s, harm); instrument_morph(s, .3f);
        // Plaits: band-pass AND high-pass at the same 150 Hz·2^(6·tone), i.e. ~500 Hz at a
        // typical tone, not the 5-9 kHz high-pass this first had (3-7x too bright, measured)
        instrument_filter(s, FILTER_BAND, (int)fminf(16000, 150 * powf(2, 6 * tone)), 1); break;
    case M_FM:        // Plaits 2-op FM: ratio, index, feedback — the same three knobs
        instrument(s, INSTR_FM, A, D, 0, 60);
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape * .6f); break;
    case M_VA:        // Plaits VA: detuned pair; past half-tone the sync range opens
        instrument(s, INSTR_SAW, A, D, 0, 60); instrument_bandlimit(s, 1);
        instrument_unison(s, 2, .04f + harm * .35f);
        instrument_sync(s, tone > .5f ? 1 + (tone - .5f) * 5 : 0); break;
    case M_RINGS:     // Rings modal resonator: Elements route = brightness / damping, struck
        instrument(s, INSTR_MODAL, 0, 6000, 0, 300);
        instrument_mode(s, MODE_MODAL_MAP, 1); instrument_mode(s, MODE_MODAL_EXCITE, 0);
        instrument_mode(s, MODE_MODAL_POS, .22f + .18f * tone);
        instrument_harmonics(s, harm); instrument_timbre(s, tone * (.6f + .4f * tone));
        instrument_morph(s, 1 - dec * .9f); break;      // their damping knob is LENGTH; ours is damping
    case M_HARMONIC:  // Plaits additive: nearest shipped additive is the drawbar organ
        instrument(s, INSTR_ORGAN, A, D, 0, 80);
        instrument_harmonics(s, harm * .85f); instrument_timbre(s, tone * (.55f + .45f * tone)); instrument_morph(s, 0); break;
    case M_CHOIR:     // three sines voicing a triad (chord type = harm), spread = shape
        instrument(s, tone > .55f ? INSTR_TRI : INSTR_SINE, A, D, 0, 80); break;
    case M_BASS:      // a round fundamental, plus a sub an octave down (= harm)
        instrument(s, tone > .6f ? INSTR_TRI : INSTR_SINE, A, D, 0, 60);
        instrument(l, INSTR_SINE, A, D, 0, 60); instrument_level(l, .3f * harm / .68f); break;
    case M_ELEMENTS: {// Elements: exciter (mallet / plectrum / particles) into the resonator
        instrument(s, INSTR_MODAL, 0, 6000, 0, 300);
        instrument_mode(s, MODE_MODAL_MAP, 1);
        instrument_mode(s, MODE_MODAL_EXCITE, t->shape < 334 ? 0 : t->shape < 667 ? .15f : .5f);
        instrument_mode(s, MODE_MODAL_POS, .2f + .16f * tone);
        instrument_harmonics(s, fminf(.999f, harm)); instrument_timbre(s, tone * (.6f + .4f * tone));
        instrument_morph(s, 1 - dec * .8f); } break;
    case M_MELLOW:    // two slowly drifting sines + a soft odd-harmonic triangle (tone)
        instrument(s, tone > .4f ? INSTR_TRI : INSTR_SINE, A, D, 0, 80);
        instrument_unison(s, 2, .02f + .1f * shape); break;
    case M_SATIN: case M_SPECTRAL:   // rounded wavetable morph between two detuned oscillators
        instrument(s, INSTR_WAVESCAN, A, D, 0, 80);
        instrument_harmonics(s, harm * (m == M_SPECTRAL ? .7f : .45f));
        instrument_timbre(s, shape * (m == M_SPECTRAL ? .5f : .3f)); instrument_morph(s, 0); break;
    case M_VELVET:    // 2-op phase modulation, ratio 1..4, the felt tine fading into its body
        instrument(s, INSTR_FM, A, D, 0, 80);
        instrument_harmonics(s, harm * .3f); instrument_timbre(s, .05f + tone * .35f); instrument_morph(s, 0);
        instrument_env(s, 0, ENV_TIMBRE, 0, 240, .3f + .6f * tone); break;
    // ── ours: engines Mutable Dreams never had, for our own biomes ──
    case M_TABLA:     // INSTR_MEMBRANE: harm = HEAD (0 tuned tabla → 1 djembe thud), tone = STRIKE
                      // (centre thump → edge slap), shape = the bayan's pitch swoop, decay = ring (gate)
        instrument(s, INSTR_MEMBRANE, 1, 0, 7, 250);
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape); break;
    case M_SCRAPE:    // INSTR_SCRAPE: harm = BODY (gourd guiro → bone quijada → metal cabasa), tone =
                      // TOOTH RATE, shape = GESTURE (steady scrape → bouncing rattle), decay = stroke length
        instrument(s, INSTR_SCRAPE, 0, 0, 7, 30);
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape); break;
    // ── brew's instruments, copied from Playtime's synth.lua patches (the row's knobs ARE the patch) ──
    case M_UPRIGHT:   // hUpright: the bowed engine plucked by a FINGER on the double-bass body, dark, mono
        instrument(s, INSTR_BOWED, 4, 0, 7, 475);
        instrument_harmonics(s, harm); instrument_timbre(s, shape * .67f); instrument_morph(s, shape);
        instrument_mode(s, 0, 1); instrument_mode(s, 1, .85f); instrument_mode(s, 2, 1); instrument_mode(s, MODE_BOW_PLUCK, 1);
        instrument_mono(s, 1); instrument_vibrato(s, 0);
        instrument_filter(s, FILTER_LOW, 200 + (int)(tone * 500), 3); break;          // tone .3 = brew's 350 Hz
    case M_ORGAN:     // brewOrgan: the thin tonewheel registration, scanner chorus, 1.2 kHz, a slow Leslie
        instrument(s, INSTR_ORGAN, 12, 0, 7, 220);
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape);
        instrument_filter(s, FILTER_LOW, 1200, 0);
        instrument_leslie(s, 1, .1f, .5f, .2f, .5f); had_leslie[i] = 1; break;
    case M_GUITAR:    // brewGuitar: the guitar engine, small open shapes, 1.9 kHz
        instrument(s, INSTR_GUITAR, 2, 0, 7, 900);
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape);
        instrument_mode(s, 0, .7f); instrument_mode(s, 1, .12f);
        instrument_filter(s, FILTER_LOW, 1900, 0); break;
    case M_BELL:      // a mallet in bell material: brewBell (~150 ms), the triangles (90 ms choked, 1.8 s ringing)
        instrument(s, INSTR_MALLET, 0, bound(t->decay * 2, 20, 2000), 0, 80);   // decay = the ring in ms / 2
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape); break;
    // ── Puppetmaker's band, from Playtime's puppetmaker patches ──
    case M_TAMB:      // the CR-78 tambourine: a short noise jingle high-passed at 6.5 kHz
        instrument(s, INSTR_NOISE, 0, 220, 0, 60);
        instrument_filter(s, FILTER_HIGH, 6500, 1); break;
    case M_RHODES:    // the rhodes patch (the epiano cart's suitcase): mellow, the Rhodes detent
        instrument(s, INSTR_EPIANO, 1, 0, 7, 450);
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape); break;
    // ── the CR-78's bossa voices, from the cr78 cart (measured against real CR-78 one-shots) ──
    case M_CRKICK:    // a soft round 65 Hz sine, barely any pitch drop (NOT an 808 punch)
        instrument(s, INSTR_SINE, 0, 140, 0, 40);
        instrument_filter(s, FILTER_LOW, 320, 2);
        instrument_env(s, 0, ENV_PITCH, 0, 30, 2.0f); break;
    case M_CRRIM:     // a CLICK: a damped ~1.5 kHz swing over a faint 215 Hz knock (the layer), gone in ~5 ms
        instrument(s, INSTR_TRI, 0, 0, 7, 6);
        instrument_filter(s, FILTER_BAND, 1500, 2); instrument_release_shape(s, RELEASE_EXP);
        instrument(l, INSTR_SINE, 0, 0, 7, 8); instrument_release_shape(l, RELEASE_EXP); break;
    case M_CRMAR:     // the shortest noise burst in the box, a narrow band at 8.7 kHz
        instrument(s, INSTR_NOISE, 0, 15, 0, 8);
        instrument_filter(s, FILTER_BAND, 8700, 15); break;
    case M_NYLON:     // the bossa cart's nylon: a warm, short pluck, soft thumb, no pick brightness
        instrument(s, INSTR_PLUCK, 1, 0, 7, 120);
        instrument_filter(s, FILTER_LOW, 2200, 3);
        instrument_harmonics(s, harm); instrument_timbre(s, tone); instrument_morph(s, shape); break;
    default:          // BREATH: a pitched sine reed crossfaded (harm) with lowpassed air
        instrument(s, INSTR_SINE, A, D, 0, 120); instrument_level(s, 1 - harm);
        instrument(l, INSTR_NOISE, A, D, 0, 120);
        // their air is a ONE-POLE at coef .008+.11·tone² (= 56 + 772·tone² Hz), not a 7 kHz LP
        instrument_filter(l, FILTER_LOW, 56 + (int)(tone * tone * 772), 0);
        instrument_level(l, harm * 1.4f); break;
    }
    // the main voice slot(s): s, plus the snare's round-robin copies, which mirror s exactly
    float gain = unit(t->level) * (S.kit && i >= 4 ? 0 : 1) * powf(10, VOICE_TRIM_DB[m] / 20);
    for (int v = 0; v < (m == M_SNARE ? SNARE_VARS : 1); v++) {
        int sl = v ? SL_ROUND + 3 * i + v - 1 : s;
        if (v) { instrument_env(sl, 1, ENV_CUTOFF_OCT, 0, 10, 0); instrument_filter(sl, FILTER_OFF, 20000, 0); }
        // the per-track filter (upstream applies it to EVERY model, drums included)
        if (t->filter && m != M_HAT) {
            float u = fminf(1, fmaxf(0, unit(t->cutoff) + (unit(S.b.macro[2]) - .5f) * .18f));
            float r = unit(t->resonance);
            if (t->filter == 3) {        // LPG: the cutoff falls .55 of the range with the decay
                instrument_filter(sl, FILTER_LOW, (int)cutoff_hz(fmaxf(0, u - .55f)), (int)(r * r * 8));
                instrument_env(sl, 1, ENV_CUTOFF_OCT, 0, 60 + (int)(dec * dec * 4000), .55f * 7);
            } else instrument_filter(sl, t->filter == 2 ? FILTER_LADDER : FILTER_LOW, (int)cutoff_hz(u), (int)(r * r * 8));
        }
        // mix: level, pan, sends (fx_level is their master return, folded into the sends here)
        instrument_level(sl, (m == M_BREATH ? 1 - harm : 1) * gain * 1.6f);
    }
    if (m == M_BASS || m == M_BREATH) instrument_level(l, (m == M_BASS ? .3f * harm / .68f : harm * 1.4f) * gain * 1.6f);
    if (m == M_CRRIM) instrument_level(l, .14f * gain * 1.6f);   // the knock ~17 dB under the click
    for (int k = 0; k < (m == M_SNARE ? SNARE_VARS + 1 : 2); k++) {
        int sl = k == 0 ? s : k == 1 ? l : SL_ROUND + 3 * i + k - 2;
        instrument_pan(sl, unit(t->pan) * 2 - 1);
        instrument_reverb(sl, fminf(.9f, unit(S.rsend[i]) * unit(S.fx_level) * 2.4f));
        instrument_echo(sl, fminf(.8f, unit(S.dsend[i]) * unit(S.fx_level) * 2.4f));
    }
}

static void apply_scene(void) {
    bpm(S.b.tempo);
    reverb(.45f + .5f * unit(S.reverb_time), .45f);
    echo(S.delay_ms, unit(S.delay_fb) * .9f, .35f);
    // the granular tape: one master cloud (upstream feeds it per track; see the doc)
    float send = 0; int n = 0;
    for (int i = 0; i < (S.kit ? 4 : 6); i++) if (!S.b.tr[i].mute) { send += unit(S.b.tr[i].send); n++; }
    send = n ? send / n : 0;
    float life_ms = 50 + unit(S.b.grain_size) * 250;
    grains(life_ms, 2000.0f / life_ms, 1 - unit(S.b.grain_pos) * .9f, .15f, unit(S.b.feedback) * .85f,
           fminf(.6f, unit(S.b.macro[3]) * send * 1.7f));
    grains_pitch((float)S.b.grain_pitch, 0, S.b.reverse);
    grains_freeze(S.b.freeze);
    if (S.b.duck_source >= 0 && S.b.duck_amount > 0) {
        sidechain_key(SL_TRACK + S.b.duck_source, 0, 1);
        for (int v = 1; v < SNARE_VARS; v++) sidechain_key(SL_ROUND + 3 * S.b.duck_source + v - 1, 0, 1);
        sidechain(0, 0, unit(S.b.duck_amount) * .9f, 1, (int)((.04f + unit(S.b.duck_release) * 1.46f) * 1000));
    } else sidechain(0, 0, 0, 1, 100);
    for (int i = 0; i < 6; i++) config_track(i);
    if (S.kit && kit_ready_bank != S.kit_bank) kit_render(S.kit_bank);
    for (int p = 0; p < 8; p++) {
        instrument_level(SL_PAD + p, S.kit ? fminf(1, unit(S.b.tr[3].level) * 1.3f) : 0);
        instrument_reverb(SL_PAD + p, fminf(.9f, unit(S.rsend[3]) * unit(S.fx_level) * 2.4f));
    }
}

// Every note here is BOOKED (schedule_note_at) with its own length, and note_off_all() only
// releases HELD notes, so a booked drone or resonator would ring on into the next biome for its
// whole decay (up to 30 s). Keep each booking id and damp the ones still sounding instead
// (NEV_DAMP 1 = a ~20 ms fade: a hand on the strings, no click).
#define LIVE_N 512
static int live_id[LIVE_N]; static double live_end[LIVE_N]; static int live_w;
static void track_booking(int id, double end) {
    if (id <= 0) return;
    live_id[live_w] = id; live_end[live_w] = end; live_w = (live_w + 1) % LIVE_N;
}
static void unbook_all(void);
static void silence_all(void) {
    double at = audio_time();
    unbook_all();                                  // notes not started yet never play
    for (int k = 0; k < LIVE_N; k++)               // notes already sounding fade out now
        if (live_id[k] > 0 && live_end[k] > at) note_event_at(live_id[k], at, NEV_DAMP, 1);
    memset(live_id, 0, sizeof live_id);
    note_off_all();
}
static void unbook_all(void) {
    for (int i = 0; i < 6; i++) { unschedule(SL_TRACK + i, 0, 0); unschedule(SL_LAYER + i, 0, 0); }
    for (int k = 0; k < 18; k++) unschedule(SL_ROUND + k, 0, 0);
    for (int p = 0; p < 8; p++) unschedule(SL_PAD + p, 0, 0);
}
static void load_biome(int id) {
    silence_all();
    cur = id; scene(id); apply_scene();
    for (int i = 0; i < 6; i++) muted[i] = S.b.tr[i].mute;
#ifdef DA_SOLO                       // A/B switch: one track alone (= mdrender --solo)
    for (int i = 0; i < 6; i++) muted[i] = i != DA_SOLO;
#endif
    step = 0; seed = (unsigned)S.b.seed; seqrng = seed;
    t_next = audio_time() + 0.1;
    memset(step_t, 0, sizeof step_t); memset(hit_t, 0, sizeof hit_t);
}

// ── firing: one track hit, booked at t ──────────────────────────────────────
static void mark_hit(int i, double t) { hit_t[i][hit_w[i]++ & 7] = t; }
static int scale_step(int note, int k);
static float snare_gain = 1;     // the jam's fills play the clap softer; every factory hit is 1
static void fire(int i, int note, float vel, double t, int gate_ms) {
    const DaTrack *tr = &S.b.tr[i];
    int s = SL_TRACK + i, l = SL_LAYER + i, m = tr->model;
    int dur = gate_ms > 0 ? gate_ms : has_env(m) ? env_attack_ms(i) + env_decay_ms(i) : 2000;
    float du = unit(tr->decay);
    if (m == M_TABLA)  dur = (int)(55 * powf(1800.0f / 55, du));   // the tabla cart's RING: the hit IS the gate
    if (m == M_SCRAPE) dur = (int)(40 * powf(20, du));             // 40 ms tick .. 800 ms long scrape
    if (m == M_UPRIGHT) dur = (int)(80 * powf(15, du));            // a stopped 8th .. a ringing note
    if (m == M_ORGAN)  dur = (int)(200 * powf(12, du));            // chords held toward the next
    if (m == M_GUITAR) dur = (int)(150 * powf(12, du));
    if (m == M_BELL)   dur = bound(tr->decay * 2, 20, 2000) + 40;
    if (m == M_TAMB)   dur = 290;
    if (m == M_RHODES) dur = 3000;
    if (m == M_CRKICK) dur = 220;
    if (m == M_CRRIM)  dur = 1;
    if (m == M_CRMAR)  dur = 30;
    if (m == M_NYLON)  dur = (int)(150 * powf(12, du));                                 // the rolled chord rings ~3 s

    // Breathe: a 7..20 s sine per track that drifts the cutoff; sampled at the note (their drift
    // is continuous, ours lands per note). Tides on ambient tracks add a second, slower sway.
    float ph = (float)fmod(t / (7.0 + i * 2.3) + i * .137, 1.0);
    float breathe = unit(tr->breathe) * sinf(ph * 6.2831853f);
    float tide = 0;
    if (S.tides[i]) { float tp = (float)fmod(t / (.5 + unit(S.tides_rate[i]) * 19.5), 1.0); tide = unit(S.tides[i]) * (1 - 4 * fabsf(tp - .5f)); }
    // when it can last be heard: its length, plus a release / a resonator's own ring
    double end = t + dur / 1000.0 + (m == M_RINGS || m == M_ELEMENTS ? 7.0 : 1.0);
    NoteOpts o = {0};
    o.gain = fmaxf(.05f, fminf(1, vel));
    if (m == M_KICK) o.gain = (3 + 7 * vel) / 10;   // Plaits: accent sets the pulse height 3+7a
    if (m == M_SNARE) o.gain = snare_gain;          // rendered at accent .8; upstream drums ignore velocity in the mix
    o.cutoff_oct = (breathe * .13f + tide * .2f) * 7.0f;
    if (m == M_ORGAN || m == M_GUITAR || m == M_NYLON) {   // the organ ROOTLESS (3 5 7 9), a guitar a small shape
        static const int organ_deg[4] = { 2, 4, 6, 8 };
        int guitar_deg[3] = { 2, 4, 7 };
        if (S.jam && DA_OWN_JAM[S.jam - 1].gtr[0]) for (int k = 0; k < 3; k++) guitar_deg[k] = DA_OWN_JAM[S.jam - 1].gtr[k];
        const int *dg = m == M_ORGAN ? organ_deg : guitar_deg; int nd = m == M_ORGAN ? 4 : 3;
        for (int k = 0; k < nd; k++) {
            int n = note; for (int st = 0; st < dg[k]; st++) { n++; while (quantize(n, S.b.root, S.b.scale) != n) n++; }
            NoteOpts c = o; c.gain = o.gain * (m == M_ORGAN ? .7f : .75f);
            // the organ's keys together a hair behind, the guitar a quick down-strum (Playtime's feel)
            double at = t + (m == M_ORGAN ? .008 : m == M_NYLON ? .004 + k * .008 : .018 + k * .012);   // nylon: a thumb's quick brush
            track_booking(schedule_note_at(at, n, s, 7, dur, &c), end + .1);
        }
        mark_hit(i, t); return;
    }
    if (S.jam && DA_OWN_JAM[S.jam - 1].pair[i]) {   // a pair (the bongos): low, high in turn
        static int pflip[6]; if (pflip[i]++ & 1) note += DA_OWN_JAM[S.jam - 1].pair[i];
    }
    if (m == M_RHODES && S.jam && (DA_OWN_JAM[S.jam - 1].keys[1] || DA_OWN_JAM[S.jam - 1].keys[0])) {
        // a jazz voicing in the scale, rolled gently upward (a biome's keys[]: e.g. stacked fourths)
        const signed char *kd = DA_OWN_JAM[S.jam - 1].keys;
        for (int k = 0; k < 6 && (k == 0 || kd[k]); k++) {
            int n = scale_step(note, kd[k]);
            NoteOpts c = o; c.gain = o.gain * .55f;
            track_booking(schedule_note_at(t + k * .028, n, s, 7, dur, &c), end + 3);
        }
        mark_hit(i, t); return;
    }
    if (m == M_RHODES) {   // babirhodes' rhodes2: ONE rolled six-note chord, a hand's up-strum, as measured
        static const int iv[6] = { 0, 7, 16, 19, 21, 24 }, at_ms[6] = { 0, 29, 52, 75, 151, 191 };
        for (int k = 0; k < 6; k++) {
            NoteOpts c = o; c.gain = o.gain * .6f;
            track_booking(schedule_note_at(t + at_ms[k] / 1000.0, note + iv[k], s, 7, dur, &c), end + 3);
        }
        mark_hit(i, t); return;
    }
    if (m == M_CHOIR) {
        static const int chord[4][3] = { {0,3,7}, {0,4,7}, {0,5,7}, {0,7,12} };
        int ci = bound(tr->harm * 4 / 1001, 0, 3);
        float spread = unit(tr->shape) * (.15f + .11f * breathe) * 100;
        for (int j = 0; j < 3; j++) {
            NoteOpts c = o; c.cents = (j - 1) * spread; c.gain = o.gain * (j ? .62f : 1);
            track_booking(schedule_note_at(t, quantize(note + chord[ci][j], S.b.root, S.b.scale), s, 7, dur, &c), end);
        }
    } else {
        int pn = note;
        if (m == M_SNARE) {   // round-robin over the noise draws, as upstream draws fresh noise per hit
            static int rr[6]; int v = rr[i]++ % SNARE_VARS;
            if (v) s = SL_ROUND + 3 * i + v - 1;
        }
        track_booking(schedule_note_at(t, pn, s, 7, dur, &o), end);
        if (m == M_CRRIM) track_booking(schedule_note_at(t, 57, l, 7, 1, &o), end);   // the faint low knock
        if (m == M_BASS)   track_booking(schedule_note_at(t, note - 12, l, 7, dur, &o), end);
        if (m == M_BREATH) track_booking(schedule_note_at(t, note, l, 7, dur, &o), end);
    }
    mark_hit(i, t);
}
static int kit_hits;
static void kit_fire(int pad, float vel, double t) {
    kit_hits++;
    NoteOpts o = {0}; o.gain = vel;
    track_booking(schedule_note_at(t, 60, SL_PAD + pad, 7, 900, &o), t + 1.0);
    mark_hit(3, t);
}

// ── tick(): one sixteenth, ported from dreams.cpp ────────────────────────────
static double step_dur(unsigned st) { return 60.0 / (S.b.tempo * 4.0) * (1 + (st % 2 ? -1 : 1) * unit(S.b.swing) * .5); }
// ── the jam arranger (our own biomes only): which layers play this 8-bar phrase ──────────────
// After Playtime's drum jam: layers enter one phrase at a time, then the set breathes — a layer
// rests for a phrase, or a BREAKDOWN takes the kick, clap and bass away and the next phrase drops
// them all back at once. The last bar of a phrase is a FILL: the clap runs up its last steps (a
// rising roll out of a breakdown) and the hats let go before the one. Its rolls come from its OWN
// rng, so the tracks' chance rolls stay exactly the factory sequencer's.
static void jam_phrase(void) {
    const JamCfg *j = &DA_OWN_JAM[S.jam - 1];
    const int *build = j->build, *rest = j->rest;
    int p = S.jam_phrase++, was_break = S.jam_break;
    unsigned r = rword(&S.jam_rng);
    S.jam_break = 0;
    for (int i = 0; i < 6; i++) S.jam_out[i] = 0;
    if (p < 5) { for (int k = p + 2; k < 6; k++) S.jam_out[build[k]] = 1; return; }
    if (was_break) return;                               // the drop: everyone back at once
    if (r % 100 < 18) { S.jam_break = 1; for (int i = 0; i < 6; i++) S.jam_out[i] = (j->break_mask >> i) & 1; return; }
    if ((r >> 8) % 100 < 55) S.jam_out[rest[(r >> 16) % 4]] = 1;
}

// ── an EVOLVING biome: one small mutation every 4 bars ──────────────────────────────────────────
static int pitched(int m) { return m != M_KICK && m != M_SNARE && m != M_HAT && m != M_SCRAPE && m != M_TAMB && m < M_CRKICK; }
static int scale_step(int note, int k) {          // move a note k steps along the scale (k < 0 = down)
    for (int n = 0; n < (k < 0 ? -k : k); n++) {
        note += k < 0 ? -1 : 1;
        while (quantize(note, S.b.root, S.b.scale) != note) note += k < 0 ? -1 : 1;
    }
    return note;
}
static void config_track(int i);
static void evolve_step(void) {
    const char *name[6]; for (int k = 0; k < 6; k++) name[k] = DA_OWN_JAM[S.jam - 1].names[k];
    unsigned r = rword(&S.jam_rng), r2 = rword(&S.jam_rng);
    int i = r % 6, up = (r >> 4) & 1, op = (r >> 8) % 100;
    DaTrack *t = &S.b.tr[i]; const DaTrack *h = &S.home[i];
    int sounding = 0; for (int k = 0; k < 6; k++) sounding += S.b.tr[k].hits > 0;
    S.gen++;
    if (op < 25) {                                   // the rubber band: one changed value steps back home
        for (int n = 0; n < 6; n++) {
            int k = (i + n) % 6; DaTrack *u = &S.b.tr[k]; const DaTrack *hk = &S.home[k];
            if (u->hits != hk->hits)     { u->hits += u->hits < hk->hits ? 1 : -1; snprintf(S.change, sizeof S.change, "%s back toward %d hits", name[k], hk->hits); return; }
            if (u->length != hk->length) { u->length += u->length < hk->length ? 1 : -1; if (u->hits > u->length) u->hits = u->length; snprintf(S.change, sizeof S.change, "%s back toward %d steps", name[k], hk->length); return; }
            if (u->note != hk->note)     { u->note = scale_step(u->note, u->note < hk->note ? 1 : -1); snprintf(S.change, sizeof S.change, "%s steps back home", name[k]); return; }
            if (u->rotate != hk->rotate) { u->rotate = hk->rotate; snprintf(S.change, sizeof S.change, "%s back in place", name[k]); return; }
            if (u->tone != hk->tone)     { u->tone += u->tone < hk->tone ? 50 : -50; if (abs(u->tone - hk->tone) < 50) u->tone = hk->tone; config_track(k); snprintf(S.change, sizeof S.change, "%s colour settles", name[k]); return; }
        }
        op = 25 + (r2 % 75);                         // nothing to relax: mutate after all
    }
    if (op >= 88 && op < 94 && t->model >= M_CRKICK) op = 0;   // the CR-78 voices have no tone knob: a hit instead
    if (op < 50) {                                   // a hit more, or one less (never below three tracks sounding)
        if (!up && t->hits <= 1 && sounding <= 3) up = 1;
        if (up && t->hits < t->length - 1) t->hits++; else if (t->hits > 0) t->hits--; else t->hits++;
        snprintf(S.change, sizeof S.change, "%s now %d in %d", name[i], t->hits, t->length);
    } else if (op < 64) {                            // the pattern turns
        t->rotate = (t->rotate + 1 + r2 % 3) % (t->length ? t->length : 1);
        snprintf(S.change, sizeof S.change, "%s shifts its pattern", name[i]);
    } else if (op < 76) {                            // the cycle grows or shrinks (5..16 steps)
        t->length = bound(t->length + (up ? 1 : -1), 5, 16);
        if (t->hits > t->length - 1) t->hits = t->length - 1;
        snprintf(S.change, sizeof S.change, "%s cycle now %d steps", name[i], t->length);
    } else if (op < 88 && pitched(t->model)) {       // a melody note moves, at most a fifth from home
        int n = scale_step(t->note, (up ? 1 : -1) * (1 + (int)(r2 % 2)));
        if (abs(n - h->note) <= 7) t->note = n;
        snprintf(S.change, sizeof S.change, "%s note moves %s", name[i], up ? "up" : "down");
    } else if (op < 94) {                            // a tone nudge
        t->tone = bound(t->tone + (up ? 80 : -80), 50, 950); config_track(i);
        snprintf(S.change, sizeof S.change, "%s turns %s", name[i], up ? "brighter" : "darker");
    } else {                                         // a canon: take another track's rhythm, a step behind
        int j = (i + 1 + (int)(r2 % 5)) % 6; const DaTrack *o = &S.b.tr[j];
        if (o->hits > 0) { t->hits = o->hits; t->length = o->length; t->rotate = (o->rotate + o->length - 1) % o->length; }
        snprintf(S.change, sizeof S.change, "%s echoes %s", name[i], name[j]);
    }
}

static void tick(double t) {
    double dur = step_dur(step);
    int evolving = S.jam && DA_OWN_JAM[S.jam - 1].evolve;
    if (evolving) { if (step && step % 64 == 0) evolve_step(); }
    else if (S.jam && step % 128 == 0) jam_phrase();
    int bar_step = step % 16, fill = S.jam && !evolving && step % 128 >= 112 && S.jam_phrase > 3;
    int fill_tr = S.jam ? DA_OWN_JAM[S.jam - 1].fill : -1, letgo_tr = S.jam ? DA_OWN_JAM[S.jam - 1].letgo : -1;
    if (step % 32 == 0) { if (S.b.locked) seqrng = seed; else seed = rword(&seqrng) | 1; }
    static const int degree[7] = { 0, 2, 3, 5, 7, 10, 12 };
    for (int i = 0; i < (S.kit ? 4 : 6); i++) {
        const DaTrack *tr = &S.b.tr[i];
        int speed = tr->speed < 1 ? 1 : tr->speed;
        if (S.kit && i == 3) {
            if (step % speed == 0 && !muted[3]) {
                unsigned at = (step / speed) % 16;
                for (int p = 0; p < 8; p++) if ((S.kit_gates[p] >> at) & 1u)
                    if (rword(&seqrng) % 1000 < (unsigned)tr->prob) kit_fire(p, at % 4 ? .67f : .8f, t);
            }
            continue;
        }
        if (step % speed) continue;
        unsigned local = step / speed;
        int hits = bound(tr->hits + (S.b.macro[0] - 500) * tr->length / 1500, 0, tr->length);
        unsigned roll = rword(&seqrng);
        if (S.seq_on[i]) {
            const Step *st = &S.seq[i][local % S.seq_len[i]];
            if (st->note && st->vel && !muted[i] && !S.jam_out[i] && roll % 100 < st->chance && (roll / 100) % 1000 < (unsigned)tr->prob) {
                int note = st->note;
                if (tr->model >= M_FM) { if (S.chord_tracks & (1u << i)) note += chord_offset(); note = quantize(note + S.b.transpose, S.b.root, S.b.scale); }
                double span = 60.0 / (S.b.tempo * 4.0) * speed;
                fire(i, note, st->vel * .01f, t, (int)(span * st->gate * 10));
            }
            continue;
        }
        if (md_hit(local, hits, tr->length, tr->rotate) && roll % 1000 < (unsigned)tr->prob && !muted[i]
            && !S.jam_out[i] && !(fill && i == letgo_tr && bar_step >= 14)) {
            int note = tr->note;
            if (tr->model >= M_FM) {
                // chords, pitched pairs and the CR-78 voices keep their pitch; a lone bell (Mipo Band's
                // triangle) wanders with the jump macro like a melody, so it does not get old
                int pair = S.jam && DA_OWN_JAM[S.jam - 1].pair[i];
                int still = tr->model == M_ORGAN || tr->model == M_GUITAR || (tr->model == M_BELL && pair) || tr->model >= M_CRKICK;   // chords and bells keep their pitch
                if (!still && (roll >> 10) % 1000 < (unsigned)S.b.macro[1]) note += degree[(roll >> 20) % 7];
                if (S.chord_tracks & (1u << i)) note += chord_offset();
                note = quantize(note + S.b.transpose, S.b.root, S.b.scale);
            }
            float vel = .8f + unit(tr->accent) * ((local % tr->length) == 0 ? .2f : -.25f);
            int rat = tr->ratchet < 1 ? 1 : tr->ratchet;
            for (int r = 0; r < rat; r++) fire(i, note, vel, t + r * dur / rat, 0);
        }
    }
    if (fill && fill_tr >= 0 && !muted[fill_tr]) {   // the phrase-end fill: a run-up, or a roll out of a breakdown
        const DaTrack *ft = &S.b.tr[fill_tr];
        int sp = ft->speed < 1 ? 1 : ft->speed;
        int on_beat = step % sp == 0 && md_hit(step / sp, bound(ft->hits + (S.b.macro[0] - 500) * ft->length / 1500, 0, ft->length), ft->length, ft->rotate);
        float g = S.jam_break ? .25f + .6f * bar_step / 15 : bar_step == 13 ? .45f : bar_step == 14 ? .6f : bar_step == 15 ? .75f : 0;
        if (g > 0 && (S.jam_break || !on_beat)) {     // never doubles a hit the track plays anyway
            int note = ft->note;
            if (ft->model >= M_FM) note = quantize(note + (S.jam_break ? bar_step / 4 * 2 : 0) + S.b.transpose, S.b.root, S.b.scale);
            if (ft->model == M_SNARE) { snare_gain = g; fire(fill_tr, note, .8f, t, 0); snare_gain = 1; }
            else fire(fill_tr, note, g, t, 0);
        }
    }
    step_t[step & 63] = t; step_n[step & 63] = step;
    step++;
}

// ── frame loop ───────────────────────────────────────────────────────────────
static void go(int d) {
    pos = (pos + d + DA_ALL) % DA_ALL;
    load_biome(browse_id(pos));
}
void init(void) {
#ifdef DA_ID                         // open on a biome by its upstream ID (= mdrender's argument)
    for (int k = 0; k < DA_ALL; k++) if (browse_id(k) == DA_ID) pos = k;
#endif
    for (int p = 0; p < 8; p++) instrument(SL_PAD + p, INSTR_SAMPLE, 0, 2000, 7, 30);
    load_biome(browse_id(pos));
}
void update(void) {
    if (btnp(0, BTN_RIGHT)) go(1);
    if (btnp(0, BTN_LEFT))  go(-1);
    if (keyp(KEY_SPACE)) { playing = !playing; if (playing) { t_next = audio_time() + .05; } else { silence_all(); } }
    for (int i = 0; i < 6; i++) if (keyp('1' + i)) muted[i] = !muted[i];
    if (playing) while (t_next < audio_time() + LOOKAHEAD) { double t = t_next; t_next += step_dur(step); tick(t); }
#ifdef DE_TRACE
    watch("biome", "%d", cur);
    watch("step", "%u", step);
    watch("kit", "%d %d %d", S.kit, kit_hits, muted[3]);
    watch("gen", "%d %s", S.gen, S.change);
    watch("jam", "%d %d %d%d%d%d%d%d", S.jam_phrase, S.jam_break, S.jam_out[0], S.jam_out[1], S.jam_out[2], S.jam_out[3], S.jam_out[4], S.jam_out[5]);
#endif
}

// the step that is SOUNDING now (booked ones are ahead of the ear)
static int sounding_step(void) {
    double at_now = audio_time(); int best = -1; double bt = -1;
    for (int k = 0; k < 64; k++) if (step_t[k] > 0 && step_t[k] <= at_now && step_t[k] > bt) { bt = step_t[k]; best = (int)step_n[k]; }
    return best;
}
static float hit_glow(int i) {
    double at_now = audio_time(), g = 0;
    for (int k = 0; k < 8; k++) { double d = at_now - hit_t[i][k]; if (hit_t[i][k] > 0 && d >= 0 && d < .25) g = fmax(g, 1 - d / .25); }
    return (float)g;
}

