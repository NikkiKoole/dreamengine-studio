        if (arch == 4) {
            S.kit = 1; S.kit_bank = var % 5; kit_pattern(var % 4);
            S.b.tr[3].level = 700; S.b.tr[3].send = 170; S.rsend[3] = 110;
        }
        if (arch == 0 || arch == 2 || arch == 5) { S.chord_pattern = 5 + var % 4; S.chord_bars = 4; S.chord_tracks = arch == 2 ? 0x24 : 0x35; }
