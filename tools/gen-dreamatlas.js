#!/usr/bin/env node
// gen-dreamatlas.js — GENERATE runtime/dreamatlas/biomes.h, the factory BIOME atlas the `dreamatlas`
// cart plays, from Mutable Dreams' own presets/catalog.json.
//
//   node tools/gen-dreamatlas.js <path/to/mutable-dreams/presets/catalog.json> [--sha <commit>]
//   node tools/gen-dreamatlas.js <catalog.json> --check     exit 1 if the committed header is stale
//
// WHY a generator and not a hand-port: a biome is ~150 integers (6 tracks × 22 fields + the scene),
// and there are 157 of them. Transcribing that by hand is how a field gets shifted by one and a
// whole family plays the wrong voice. The catalog is the upstream's OWN browser-side copy of the
// flash atlas (tools/generate_presets.py writes both), so reading it is reading the factory data.
//
// SOURCE + LICENCE: github.com/kidbee85-beep/mutable-dreams, tag v1.4 (Kid Bunka / Christoph Link).
// The preset atlas is generated by their tools/generate_presets.py, "MIT" in its header
// (preset_bank.inc) and "MIT OR GPL-3.0-only" for the DSP; we take it under MIT with credit.
// The catalog itself is NOT committed here (697 KB, most of it tone presets the cart does not use) —
// clone the tag and point this tool at it. The emitted header records which commit it came from.
//
// What is emitted, and what is NOT: only the FactoryPatch prefix of each biome (the scene fields +
// six md_track rows, in md_track's own field order) plus names, families and the curated browse
// order. Everything upstream's scene() DERIVES in code (fx sends by family, chord journeys, the
// Velvet Keys phrases, the Lo-Fi kit) is ported by hand in the cart, because it is code, not data.
// Design + the voice mapping: docs/design/mutable-dreams.md
'use strict';
const fs = require('fs');
const path = require('path');

const OUT = path.join(__dirname, '..', 'runtime', 'dreamatlas', 'biomes.h');
const TRACK_FIELDS = ['model', 'tone', 'harm', 'decay', 'level', 'send', 'hits', 'length', 'rotate', 'prob',
  'note', 'pan', 'mute', 'speed', 'attack', 'ratchet', 'accent', 'shape', 'cutoff', 'resonance', 'filter', 'breathe'];
const SCENE_FIELDS = ['family', 'tempo', 'root', 'scale', 'seed', 'locked', 'freeze', 'grain_size', 'grain_pos',
  'feedback', 'transpose', 'swing', 'grain_pitch', 'reverse', 'duck_source', 'duck_amount', 'duck_release'];

function emit(cat, sha) {
  const b = cat.biomes;
  if (!Array.isArray(b) || !b.length) throw new Error('catalog has no biomes[]');
  b.forEach((x, i) => {
    if (x.id !== i) throw new Error(`biome ${i} has id ${x.id}: the atlas index must equal the id`);
    if (!Array.isArray(x.tracks) || x.tracks.length !== 6) throw new Error(`biome ${i} (${x.name}) does not have 6 tracks`);
    for (const t of x.tracks) for (const f of TRACK_FIELDS) if (typeof t[f] !== 'number') throw new Error(`biome ${i} track field ${f} missing`);
    for (const f of SCENE_FIELDS) if (typeof x[f] !== 'number') throw new Error(`biome ${i} scene field ${f} missing`);
  });
  const q = (s) => JSON.stringify(String(s));
  const L = [];
  L.push('/* GENERATED by tools/gen-dreamatlas.js — do not hand-edit. */');
  L.push('/* Source: github.com/kidbee85-beep/mutable-dreams v1.4 presets/catalog.json' + (sha ? ' @ ' + sha : '') + ' */');
  L.push('/* Factory atlas by Kid Bunka / Christoph Link (MIT, from tools/generate_presets.py). */');
  L.push('/* See docs/design/mutable-dreams.md for the mapping onto dreamengine voices. */');
  L.push('#pragma once');
  L.push(`#define DA_BIOMES ${b.length}`);
  L.push(`#define DA_FAMILIES ${cat.families.length}`);
  L.push('/* one track row, in upstream md_track field order */');
  L.push('typedef struct { int ' + TRACK_FIELDS.join(', ') + '; } DaTrack;');
  L.push('typedef struct { const char *name; int ' + SCENE_FIELDS.join(', ') + '; int macro[4]; DaTrack tr[6]; } DaBiome;');
  L.push('static const char *const DA_FAMILY_NAME[DA_FAMILIES] = {' + cat.families.map(q).join(', ') + '};');
  L.push('static const char *const DA_FAMILY_SHORT[DA_FAMILIES] = {' + cat.family_short.map(q).join(', ') + '};');
  L.push('static const DaBiome DA_BIOME[DA_BIOMES] = {');
  for (const x of b) {
    const sc = SCENE_FIELDS.map((f) => x[f]).join(',');
    const tr = x.tracks.map((t) => '{' + TRACK_FIELDS.map((f) => t[f]).join(',') + '}').join(',');
    L.push(` {${q(x.name)},${sc},{${x.macro.join(',')}},{${tr}}},`);
  }
  L.push('};');
  L.push('/* the curated wheel order: neighbours are meant to feel genuinely different */');
  L.push(`static const unsigned char DA_BROWSE[${cat.browse_order.length}] = {` + cat.browse_order.join(',') + '};');
  return L.join('\n') + '\n';
}

function main() {
  const args = process.argv.slice(2);
  const src = args.find((a) => !a.startsWith('--') && args[args.indexOf(a) - 1] !== '--sha');
  const si = args.indexOf('--sha');
  const sha = si >= 0 ? args[si + 1] : null;
  if (!src) { console.error('usage: node tools/gen-dreamatlas.js <catalog.json> [--sha <commit>] [--check]'); process.exit(2); }
  const text = emit(JSON.parse(fs.readFileSync(src, 'utf8')), sha);
  if (args.includes('--check')) {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== text) { console.error('✗ runtime/dreamatlas/biomes.h is stale vs ' + src); process.exit(1); }
    console.log('✓ runtime/dreamatlas/biomes.h up to date');
    return;
  }
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, text);
  console.log(`wrote ${path.relative(process.cwd(), OUT)} (${text.length} bytes)`);
}
main();
