#!/usr/bin/env node
// gen-steinway.js — GENERATE runtime/steinway.h: the 13 Steinway recordings in assets/samples/steinway/,
// packed into the cart so the hybrid grand works where a cart cannot read assets/ (web, app, AUv3).
//
//   node tools/gen-steinway.js               # write runtime/steinway.h
//   node tools/gen-steinway.js --check       # exit nonzero if the header is stale
//   node tools/gen-steinway.js --selfcheck   # the C decoder vs this file's decoder (bit-exact) + per-zone SNR
//
// WHAT IT IS FOR. INSTR_PIANO's hybrid (instrument_piano_attack): each note plays the REAL recording,
// then fades into the modelled string. The hand-over has to be LATE (2.6 s, 0.5 s fade): measured by
// ear 2026-11-09, a 70-300 ms splice is plainly audible because the two strings still differ in tone
// colour that early; at 2.6 s nobody hears it. So nearly the whole 3.2 s recording ships (the bass and
// middle are still only ~20 dB under their peak at 3.1 s; only F#6/C7 have died), and the size is set
// by the ENCODING, not by trimming.
//
// ENCODING: IMA ADPCM, 4 bits a sample (the standard tables; one stream per zone, no blocks, so no
// header per block). Measured against the 16-bit source: 35-49 dB SNR, attack and tail alike, because
// the step size follows the signal. 8-bit mu-law was worse at twice the size (25-37 dB, and its noise
// sits on the quiet tail where a piano shows it). 16-bit = 3.5 MB, mu-law 1.8 MB, ADPCM ~0.9 MB.
//
// CREDIT (CC BY 4.0, required wherever this ships): "Piano: bitKlavier Grand Sample Library, Daniel
// Trueman, Princeton University (CC BY 4.0)" — the header carries it as STEINWAY_CREDIT; show it.
const fs = require('fs'), path = require('path'), os = require('os'), cp = require('child_process');
const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'assets', 'samples', 'steinway');
const OUT = path.join(ROOT, 'runtime', 'steinway.h');
const ZONES = ['C1', 'Fs1', 'C2', 'Fs2', 'C3', 'Fs3', 'C4', 'Fs4', 'C5', 'Fs5', 'C6', 'Fs6', 'C7'];
const ROOT_MIDI = z => 24 + 6 * z;
const SPLICE_MS = 2600, XFADE_MS = 500;

const STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80,
    88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724,
    796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428,
    4871, 5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385,
    24623, 27086, 29794, 32767];
const IDX = [-1, -1, -1, -1, 2, 4, 6, 8, -1, -1, -1, -1, 2, 4, 6, 8];

function readWav16(file) {                       // mono 16-bit PCM
    const b = fs.readFileSync(file);
    let o = 12;
    while (o + 8 <= b.length) {
        const id = b.toString('ascii', o, o + 4), len = b.readUInt32LE(o + 4);
        if (id === 'fmt ') {
            if (b.readUInt16LE(o + 10) !== 1 || b.readUInt16LE(o + 22) !== 16 || b.readUInt32LE(o + 12) !== 44100)
                throw new Error(`${file}: need mono 16-bit 44.1 kHz`);
        }
        if (id === 'data') {
            const n = len >> 1, s = new Int16Array(n);
            for (let i = 0; i < n; i++) s[i] = b.readInt16LE(o + 8 + 2 * i);
            return s;
        }
        o += 8 + len + (len & 1);
    }
    throw new Error(`${file}: no data chunk`);
}

// one nibble step, shared by encoder and decoder so both walk the same predictor
function step(st, c) {
    const s = STEP[st.i];
    let dq = s >> 3;
    if (c & 4) dq += s;
    if (c & 2) dq += s >> 1;
    if (c & 1) dq += s >> 2;
    st.p += (c & 8) ? -dq : dq;
    if (st.p > 32767) st.p = 32767; else if (st.p < -32768) st.p = -32768;
    st.i += IDX[c];
    if (st.i < 0) st.i = 0; else if (st.i > 88) st.i = 88;
}
function encode(pcm) {
    const out = new Uint8Array((pcm.length + 1) >> 1), st = { p: 0, i: 0 };
    for (let n = 0; n < pcm.length; n++) {
        const s = STEP[st.i];
        let d = pcm[n] - st.p, c = 0;
        if (d < 0) { c = 8; d = -d; }
        if (d >= s) { c |= 4; d -= s; }
        if (d >= s >> 1) { c |= 2; d -= s >> 1; }
        if (d >= s >> 2) c |= 1;
        step(st, c);
        out[n >> 1] |= (n & 1) ? c << 4 : c;
    }
    return out;
}
function decode(bytes, n) {
    const out = new Int16Array(n), st = { p: 0, i: 0 };
    for (let k = 0; k < n; k++) { step(st, (bytes[k >> 1] >> ((k & 1) * 4)) & 15); out[k] = st.p; }
    return out;
}

function build() {
    const zones = ZONES.map((name, z) => {
        const pcm = readWav16(path.join(SRC, `${name}.wav`));
        return { name, z, n: pcm.length, pcm, data: encode(pcm) };
    });
    const total = zones.reduce((a, z) => a + z.data.length, 0);
    let h = `// GENERATED by tools/gen-steinway.js from assets/samples/steinway/ — do not edit; rerun the tool.
// steinway.h — a real Steinway D for INSTR_PIANO's hybrid grand, BAKED IN (works on web / app / AUv3).
//
// Piano: bitKlavier Grand Sample Library, Daniel Trueman, Princeton University (CC BY 4.0).
// The licence requires that credit wherever this ships: show STEINWAY_CREDIT (an about / info line).
//
// 13 recordings, C1 .. C7 every 6 semitones (MIDI 24 + 6k), 3.2 s each, IMA ADPCM 4-bit
// (${(total / 1024).toFixed(0)} KB; 35-49 dB SNR vs the 16-bit source).
//
// USE (one call does all of it):
//     instrument(5, INSTR_PIANO, 1, 0, 7, 120);   // + harmonics 0.08 / morph etc. as for the grand
//     steinway_attach(5, 0);                      // decode into sample slots 0..12 + register the zones
//   Two piano slots? steinway_load(0) once, then steinway_use(slot, 0) on each; steinway_detach(slot)
//   returns a slot to the model alone.
//   Every note then plays the REAL recording and fades into the modelled string at 2.6 s, so a held
//   note rings on past the 3.2 s the recording lasts. STEINWAY_ZONES (13) of the 16 sample slots are
//   used, starting at first_sample_slot. Decoding takes a few ms; do it once, in init().
// WHY 2.6 s: a 70-300 ms splice was plainly audible (the strings differ in tone colour that early).
#ifndef STEINWAY_H
#define STEINWAY_H
#include <stdlib.h>

#define STEINWAY_ZONES     ${ZONES.length}
#define STEINWAY_SPLICE_MS ${SPLICE_MS}   // the recording plays this long ...
#define STEINWAY_XFADE_MS  ${XFADE_MS}    // ... then fades into the model over this
static const char STEINWAY_CREDIT[] = "Piano: bitKlavier Grand Sample Library, Daniel Trueman, Princeton University (CC BY 4.0)";

`;
    for (const z of zones) {
        h += `static const unsigned char steinway_${z.name}[${z.data.length}] = {\n`;
        for (let i = 0; i < z.data.length; i += 40) h += Array.from(z.data.subarray(i, i + 40)).join(',') + ',\n';
        h += `};\n`;
    }
    h += `
static const struct { const unsigned char *adpcm; int samples; int root_midi; } STEINWAY_ZONE[STEINWAY_ZONES] = {
${zones.map(z => `    { steinway_${z.name}, ${z.n}, ${ROOT_MIDI(z.z)} },`).join('\n')}
};

// decode one zone's IMA ADPCM into floats (-1..1); out must hold STEINWAY_ZONE[z].samples
static inline void steinway_decode(int z, float *out) {
    static const short st[89] = { ${STEP.join(',')} };
    static const signed char ix[16] = { ${IDX.join(',')} };
    const unsigned char *d = STEINWAY_ZONE[z].adpcm;
    int p = 0, i = 0;
    for (int k = 0; k < STEINWAY_ZONE[z].samples; k++) {
        int c = (d[k >> 1] >> ((k & 1) * 4)) & 15, s = st[i], dq = s >> 3;
        if (c & 4) dq += s;
        if (c & 2) dq += s >> 1;
        if (c & 1) dq += s >> 2;
        p += (c & 8) ? -dq : dq;
        if (p > 32767) p = 32767; else if (p < -32768) p = -32768;
        i += ix[c]; if (i < 0) i = 0; else if (i > 88) i = 88;
        out[k] = (float)p / 32768.0f;
    }
}

// decode all 13 into sample slots first_sample_slot .. +12; returns the number loaded
static inline int steinway_load(int first_sample_slot) {
    int n = 0;
    for (int z = 0; z < STEINWAY_ZONES; z++) {
        float *buf = (float *)malloc((size_t)STEINWAY_ZONE[z].samples * sizeof(float));
        if (!buf) break;
        steinway_decode(z, buf);
        sample_load(first_sample_slot + z, buf, STEINWAY_ZONE[z].samples);   // sample_load copies
        free(buf);
        n++;
    }
    return n;
}

// point a piano slot at recordings ALREADY loaded (steinway_load): switch it to the Steinway-matched
// model (MODE_PIANO_MODEL) and register every zone with the late hand-over. Several slots can share
// one loaded set — load once, use per slot.
static inline void steinway_use(int instr_slot, int first_sample_slot) {
    instrument_mode(instr_slot, MODE_PIANO_MODEL, 1.0f);
    for (int z = 0; z < STEINWAY_ZONES; z++)
        instrument_piano_attack(instr_slot, first_sample_slot + z, STEINWAY_ZONE[z].root_midi,
                                STEINWAY_SPLICE_MS, STEINWAY_XFADE_MS);
}

// back to the modelled grand alone on that slot (the recordings stay loaded)
static inline void steinway_detach(int instr_slot) {
    for (int z = 0; z < STEINWAY_ZONES; z++) instrument_piano_attack(instr_slot, -1, STEINWAY_ZONE[z].root_midi, 0, 0);
}

// the whole hybrid in one call: load the recordings, then use them on this slot
static inline void steinway_attach(int instr_slot, int first_sample_slot) {
    if (steinway_load(first_sample_slot) == STEINWAY_ZONES) steinway_use(instr_slot, first_sample_slot);
}
#endif
`;
    return { h, zones, total };
}

const arg = process.argv[2];
const { h, zones, total } = build();
if (arg === '--check') {
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== h) { console.log('✗ runtime/steinway.h is STALE — run node tools/gen-steinway.js'); process.exit(1); }
    console.log('✓ runtime/steinway.h up to date'); process.exit(0);
}
if (arg === '--selfcheck') {
    let bad = 0;
    // 1. the codec: every zone decodes to within 30 dB of its source (and a CORRUPTED stream must not)
    for (const z of zones) {
        const d = decode(z.data, z.n);
        let s = 0, e = 0; for (let i = 0; i < z.n; i++) { s += z.pcm[i] ** 2; e += (z.pcm[i] - d[i]) ** 2; }
        const snr = 10 * Math.log10(s / e);
        if (snr < 30) { console.log(`✗ ${z.name}: SNR ${snr.toFixed(1)} dB < 30`); bad++; }
        else console.log(`✓ ${z.name}: SNR ${snr.toFixed(1)} dB`);
    }
    const c = zones[6].data.slice(); c[1000] ^= 0x88;            // negative control: one flipped byte
    const dc = decode(c, zones[6].n), d0 = decode(zones[6].data, zones[6].n);
    let diff = 0; for (let i = 0; i < zones[6].n; i++) diff += dc[i] !== d0[i] ? 1 : 0;
    if (diff === 0) { console.log('✗ control: a corrupted stream decoded identically (decoder ignores its input)'); bad++; }
    else console.log(`✓ control: a corrupted byte changes ${diff} samples`);
    // 2. the C decoder in the EMITTED header must match this file's decoder bit-exactly (zone C4)
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gsw-'));
    fs.writeFileSync(path.join(dir, 'steinway.h'), h);
    fs.writeFileSync(path.join(dir, 't.c'), `#include <stdio.h>
void sample_load(int a, const float *b, int c) {} void instrument_mode(int a, int b, float c) {}
void instrument_piano_attack(int a, int b, int c, int d, int e) {}
#define MODE_PIANO_MODEL 6
#include "steinway.h"
int main(void) { static float o[400000]; steinway_decode(6, o); fwrite(o, 4, STEINWAY_ZONE[6].samples, stdout); return 0; }`);
    cp.execSync(`clang -O1 -o ${dir}/t ${dir}/t.c -I${dir}`);
    const raw = cp.execSync(`${dir}/t`, { maxBuffer: 1 << 24 });
    const cf = new Float32Array(raw.buffer, raw.byteOffset, raw.length / 4), jd = decode(zones[6].data, zones[6].n);
    let mism = 0; for (let i = 0; i < jd.length; i++) if (cf[i] !== jd[i] / 32768) mism++;
    if (cf.length !== jd.length || mism) { console.log(`✗ C decoder differs from the JS one (${mism} samples, len ${cf.length}/${jd.length})`); bad++; }
    else console.log(`✓ C decoder bit-exact vs the JS decoder (${jd.length} samples)`);
    fs.rmSync(dir, { recursive: true, force: true });
    console.log(bad ? `✗ ${bad} failed` : '✓ all passed'); process.exit(bad ? 1 : 0);
}
fs.writeFileSync(OUT, h);
console.log(`wrote runtime/steinway.h — ${zones.length} zones, ${(total / 1024).toFixed(0)} KB ADPCM, ${(h.length / 1048576).toFixed(1)} MB source`);
